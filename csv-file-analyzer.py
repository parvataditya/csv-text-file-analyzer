#Q4. Create a text file containing student records in the following format:
import csv
import json
import os


CSV_FILE = "students.csv"
JSON_FILE = "students.json"


def read_csv_file():
    """Read student records from the CSV file."""
    if not os.path.exists(CSV_FILE):
        print(f"{CSV_FILE} not found.")
        return None

    with open(CSV_FILE, "r", newline="") as f:
        reader = csv.reader(f)
        rows = list(reader)

    return rows


def convert_to_dict_list(rows):
    """Convert each row into a dictionary and build a list of dictionaries."""
    students = []

    for row in rows:
        if not row:
            continue  # skip empty lines

        roll, name, course, marks = row

        student = {
            "Roll Number": roll.strip(),
            "Name": name.strip(),
            "Course": course.strip(),
            "Marks": int(marks.strip())
        }
        students.append(student)

    return students


def save_to_json(students):
    """Store the list of dictionaries into a JSON file."""
    with open(JSON_FILE, "w") as f:
        json.dump(students, f, indent=4)

    print(f"Data successfully saved to {JSON_FILE}\n")


def display_from_json():
    """Read the JSON file and display records in a formatted manner."""
    if not os.path.exists(JSON_FILE):
        print(f"{JSON_FILE} not found.")
        return

    with open(JSON_FILE, "r") as f:
        students = json.load(f)

    if not students:
        print("No records found in JSON file.\n")
        return

    print(f"\n{'Roll No':<10}{'Name':<12}{'Course':<10}{'Marks':<8}")
    print("-" * 40)
    for student in students:
        print(f"{student['Roll Number']:<10}{student['Name']:<12}"
              f"{student['Course']:<10}{student['Marks']:<8}")
    print()


def main():
    # Step 1: Read from CSV file
    rows = read_csv_file()
    if rows is None:
        return

    # Step 2: Convert to list of dictionaries
    students = convert_to_dict_list(rows)

    # Step 3: Store in JSON file
    save_to_json(students)

    # Step 4: Read JSON file and display formatted records
    display_from_json()


if __name__ == "__main__":
    main()

#Q5. Write a Python program to demonstrate the basic file-handling operations
import os


FILENAME = "demo.txt"


def demonstrate_file_handling():

    # ===================================================
    # 1. CREATE AND OPEN A FILE USING open(), MODE 'w'
    # ===================================================
    print("===== 1. Creating and opening file in 'w' mode =====")
    file = open(FILENAME, "w")
    print(f"File '{FILENAME}' created/opened in write mode.\n")
    file.close()  # closing manually here to demonstrate close()

    # ===================================================
    # 2. WRITE MODE ('w') — using write() and writelines()
    # ===================================================
    print("===== 2. Writing data using write() and writelines() =====")
    file = open(FILENAME, "w")  # 'w' overwrites existing content
    file.write("This is the first line.\n")
    file.write("This is the second line.\n")

    lines_to_add = ["This is the third line.\n", "This is the fourth line.\n"]
    file.writelines(lines_to_add)

    file.close()
    print("Data written successfully using write() and writelines().\n")

    # ===================================================
    # 3. READ MODE ('r') — using read(), readline(), readlines()
    # ===================================================
    print("===== 3. Reading data using read() =====")
    file = open(FILENAME, "r")
    content = file.read()
    print("Full content using read():\n" + content)
    file.close()

    print("===== Reading data using readline() =====")
    file = open(FILENAME, "r")
    first_line = file.readline()
    second_line = file.readline()
    print("First line:", first_line.strip())
    print("Second line:", second_line.strip())
    file.close()

    print("\n===== Reading data using readlines() =====")
    file = open(FILENAME, "r")
    all_lines = file.readlines()
    print("All lines as a list:", all_lines)
    file.close()

    # ===================================================
    # 4. APPEND MODE ('a') — adding data without overwriting
    # ===================================================
    print("\n===== 4. Appending data using 'a' mode =====")
    file = open(FILENAME, "a")
    file.write("This is an appended line.\n")
    file.close()

    file = open(FILENAME, "r")
    print("Content after appending:\n" + file.read())
    file.close()

    # ===================================================
    # 5. READ + WRITE MODE ('r+') — read and modify together
    # ===================================================
    print("===== 5. Using 'r+' mode to read and write =====")
    file = open(FILENAME, "r+")
    print("Content before modification:\n" + file.read())

    file.write("This line was added using r+ mode.\n")
    file.close()

    file = open(FILENAME, "r")
    print("Content after r+ modification:\n" + file.read())
    file.close()

    # ===================================================
    # 6. seek() AND tell()
    # ===================================================
    print("===== 6. Demonstrating seek() and tell() =====")
    file = open(FILENAME, "r")

    print("Current cursor position (start):", file.tell())

    data_chunk = file.read(10)  # read first 10 characters
    print("First 10 characters:", data_chunk)
    print("Cursor position after reading 10 chars:", file.tell())

    file.seek(0)  # move cursor back to the beginning
    print("Cursor position after seek(0):", file.tell())

    print("Re-reading from start:", file.read(10))
    file.close()

    # ===================================================
    # 7. USING with open() — AUTOMATIC FILE CLOSING
    # ===================================================
    print("\n===== 7. Using 'with open()' statement =====")
    with open(FILENAME, "r") as file:
        content = file.read()
        print("Content read using 'with open()':\n" + content)
    # File is automatically closed here — no need to call file.close()
    print("File automatically closed after 'with' block.")
    print("Is file closed?", file.closed)


if __name__ == "__main__":
    demonstrate_file_handling()

