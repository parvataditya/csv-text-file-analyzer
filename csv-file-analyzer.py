def initialize_file():
    """Create the JSON file with an empty list if it doesn't exist."""
    if not os.path.exists(FILENAME):
        with open(FILENAME, "w") as f:
            json.dump([], f)


def load_data():
    """Load all employee records from the JSON file."""
    with open(FILENAME, "r") as f:
        return json.load(f)


def save_data(data):
    """Save the employee list back to the JSON file."""
    with open(FILENAME, "w") as f:
        json.dump(data, f, indent=4)


def add_employee():
    """Add a new employee record."""
    data = load_data()

    emp_id = input("Enter Employee ID: ").strip()

    # Check for duplicate ID
    for emp in data:
        if emp["Employee ID"] == emp_id:
            print("Employee ID already exists. Cannot add duplicate.\n")
            return

    name = input("Enter Name: ").strip()
    department = input("Enter Department: ").strip()
    designation = input("Enter Designation: ").strip()

    while True:
        salary = input("Enter Salary: ").strip()
        if salary.replace(".", "", 1).isdigit():
            break
        print("Invalid salary. Please enter a number.")

    employee = {
        "Employee ID": emp_id,
        "Name": name,
        "Department": department,
        "Designation": designation,
        "Salary": float(salary)
    }

    data.append(employee)
    save_data(data)
    print("Employee record added successfully.\n")


def display_employees():
    """Display all employee records."""
    data = load_data()

    if not data:
        print("No employee records found.\n")
        return

    print(f"\n{'ID':<10}{'Name':<15}{'Department':<15}{'Designation':<15}{'Salary':<10}")
    print("-" * 65)
    for emp in data:
        print(f"{emp['Employee ID']:<10}{emp['Name']:<15}{emp['Department']:<15}"
              f"{emp['Designation']:<15}{emp['Salary']:<10}")
    print()


